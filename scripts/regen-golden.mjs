// Regenerates the golden clustering fixture from the current WASM build.
//
// The golden test pins clustering output so that *unintended* changes fail.
// Run this only when clustering output is meant to change, and say so in the
// commit message:
//
//   yarn build:wasm && node scripts/regen-golden.mjs [--eps 15] [--minPts 2]
//
// Inputs (rows, dimensions) are kept; settings and the expected result are
// rewritten. Node >= 22.18 imports the .ts fixture directly (type stripping).
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as fixture from "../src/app/actions/__fixtures__/clusteringGolden.ts";

const require = createRequire(import.meta.url);
const wasm = require("../backend/rust_wasm_module/pkg-node/rust_wasm_module.js");

const argv = process.argv.slice(2);
const arg = (name) => {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 ? argv[i + 1] : undefined;
};

const settings = { ...fixture.settings };
for (const key of ["eps", "minPts", "dataTicks"]) {
  if (arg(key) !== undefined) settings[key] = Number(arg(key));
}
if (arg("zNormalize") !== undefined) settings.zNormalize = arg("zNormalize") === "true";

const expectedResult = wasm.aggregator(fixture.inputValues, fixture.dimensions, settings);
const json = (v) => JSON.stringify(v, null, 2);

const out = `// Golden clustering fixture: input rows plus the output of the current
// clustering for \`settings\`. Generated by scripts/regen-golden.mjs with
// algorithm version "${wasm.algo_version()}". Regenerate only on purpose.
export const inputValues: Record<string, number>[] = ${json(fixture.inputValues)};

export const dimensions: string[] = ${json(fixture.dimensions)};

export const settings = ${json(settings)};

export const algoVersion = ${json(wasm.algo_version())};

export const expectedResult = ${json(expectedResult)};
`;
const target = fileURLToPath(
  new URL("../src/app/actions/__fixtures__/clusteringGolden.ts", import.meta.url)
);
writeFileSync(target, out);
console.log(
  `Wrote ${target}: ${expectedResult.aggregated.length} clusters,`,
  JSON.stringify(Object.fromEntries(expectedResult.clusterAssignment))
);
