import { expect, test } from "vitest";
import { createRequire } from "node:module";
import {
  inputValues,
  dimensions,
  settings,
  algoVersion,
  expectedResult,
} from "../../app/actions/__fixtures__/clusteringGolden";

// The WASM module is built (wasm-pack) into pkg-node for Node/vitest; the app
// uses the `web` target of the same crate inside the clustering Web Worker.
// This pins the clustering output so unintended changes fail. Intended changes
// regenerate the fixture with scripts/regen-golden.mjs.
const require = createRequire(import.meta.url);
const wasm = require(
  "../../../backend/rust_wasm_module/pkg-node/rust_wasm_module.js"
) as {
  aggregator: (
    rawData: unknown,
    dimensions: unknown,
    settings: unknown
  ) => {
    aggregated: Record<string, number>[][];
    yDomain: [number, number];
    clusterAssignment: [string, number][];
  };
  algo_version: () => string;
};

test("golden fixture was generated by the algorithm in this build", () => {
  expect(wasm.algo_version()).toBe(algoVersion);
});

test("WASM aggregator matches the golden clustering output", () => {
  const result = wasm.aggregator(inputValues, dimensions, settings);

  expect(result.aggregated.length).toBe(expectedResult.aggregated.length);
  expect(result.clusterAssignment).toStrictEqual(
    expectedResult.clusterAssignment
  );
  expect(result.yDomain).toStrictEqual(expectedResult.yDomain);
  // Full structural equality (object key order is irrelevant to toStrictEqual).
  expect(result.aggregated).toStrictEqual(expectedResult.aggregated);
});
